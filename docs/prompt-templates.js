const SCENE_MULTI_VIEW = `以这张图片为参考，生成一组2×2网格的场景图，每个面板使用明显不同的摄像机角度，添加干净的1pt白色网格线分隔所有画面（内部边缘线，不要双重加粗）。所有面板必须展示相同的环境。任何面板中都不应出现角色或人物。第一行（从左到右）：1. 正面视角：直接面向场景的平视视角。2. 仰视视角：陡峭的仰视视角，相机从水平面向上倾斜60度，从左到右水平排列。3. 特写镜头：聚焦环境关键部分的紧凑详细视角，填充大部分画面。4. 俯视广角镜头：从高处俯瞰场景的高角度视角，视野开阔。确保：每个面板的摄像机位置、高度和方向明显不同。透视变化强烈且明确。所有面板的光照和风格保持一致。不要在图片上写任何文字。`;

export const PROMPT_TEMPLATES = {
  characterTurnaround: CHARACTER_TURNAROUND,
  sceneMultiView: SCENE_MULTI_VIEW,
};

/**
 * 拼接「用户描述 + 模板」，与后端 build_*_prompt 的行为保持一致。
 * 空片段会被丢弃，非空片段之间用空行连接。
 */
function joinParts(parts) {
  return parts
    .map((part) => (typeof part === "string" ? part.trim() : ""))
    .filter(Boolean)
    .join("\n\n");
}

/** 角色三视图：用户描述在前，模板在后。 */
export function buildCharacterTurnaroundPrompt(userPrompt) {
  return joinParts([userPrompt, PROMPT_TEMPLATES.characterTurnaround]);
}

/** 场景多视角：用户描述在前，模板在后。 */
export function buildSceneMultiViewPrompt(userPrompt) {
  return joinParts([userPrompt, PROMPT_TEMPLATES.sceneMultiView]);
}
